"""Automated Unit-Test and Bug Reproduction Generator.

Synthesizes executable reproduction test cases using target function AST metadata,
specifications, and bug descriptions.
"""

from __future__ import annotations
from pathlib import Path
from typing import Any, Dict, List, Optional
from repocortex.core.types import Symbol


class TestGenerator:
    """Generates Python unittest reproduction test cases for reported bugs."""

    REPRODUCTION_TEMPLATE = '''"""Automated bug reproduction test case generated by RepoCortex."""

import unittest
{import_statement}


class TestReproduction_{class_suffix}(unittest.TestCase):
    """Reproduction tests validating fix for: {bug_summary}"""

    def test_{test_name}_reproduction(self):
        """Validates expected behavior under reported boundary conditions."""
{test_body}


if __name__ == "__main__":
    unittest.main()
'''

    @classmethod
    def generate_reproduction_test(
        cls,
        module_path: str,
        target_symbol: Symbol,
        bug_description: str,
        custom_assertions: Optional[List[str]] = None,
    ) -> str:
        """Constructs an executable unittest file reproducing the bug."""
        # Clean module path into python import
        path_obj = Path(module_path)
        parts = list(path_obj.with_suffix("").parts)
        module_import_name = ".".join(parts)

        import_stmt = f"from {module_import_name} import {target_symbol.name}"
        class_suffix = target_symbol.name.capitalize()
        test_name = f"reproduce_{target_symbol.name}"
        summary = bug_description.split("\n")[0][:80]

        if custom_assertions:
            body_lines = [f"        {a}" for a in custom_assertions]
            test_body = "\n".join(body_lines)
        else:
            # Default reproduction assertions based on symbol signature
            test_body = f"""        # Exercise {target_symbol.name} with reported problematic inputs
        # Expected to complete without crashing and return valid results
        result = {target_symbol.name}()
        self.assertIsNotNone(result)"""

        return cls.REPRODUCTION_TEMPLATE.format(
            import_statement=import_stmt,
            class_suffix=class_suffix,
            bug_summary=summary,
            test_name=test_name,
            test_body=test_body,
        )
